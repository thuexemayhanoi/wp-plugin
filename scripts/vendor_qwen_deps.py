def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def fetch(pkg: dict) -> dict[str, bytes]:
    with urllib.request.urlopen(pkg["tarball"], timeout=120) as response:
        blob = response.read()
    algo, expected = pkg["integrity"].split("-", 1)
    actual = base64.b64encode(hashlib.new(algo, blob).digest()).decode()
    if actual != expected:
        sys.exit(f"Integrity mismatch for {pkg['name']}@{pkg['version']}")
    out = {}
    with tarfile.open(fileobj=io.BytesIO(blob), mode="r:gz") as tar:
        for member, target in pkg["files"].items():
            handle = tar.extractfile(member)
            if handle is None:
                sys.exit(f"{member} missing from {pkg['name']}@{pkg['version']}")
            out[target] = handle.read()
    if pkg["name"] == "onnxruntime-web":
        out["onnxruntime-web/LICENSE"] = ORT_LICENSE.encode()
    return out


def write() -> None:
    manifest = {"note": "Generated by scripts/vendor_qwen_deps.py. Do not edit by hand.", "packages": []}
    for pkg in PACKAGES:
        files = fetch(pkg)
        entry = {k: pkg[k] for k in ("name", "version", "license", "tarball", "integrity")}
        entry["files"] = {}
        for target, data in sorted(files.items()):
            path = VENDOR / target
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
            entry["files"][target] = {"sha256": sha256(data), "bytes": len(data)}
        manifest["packages"].append(entry)
    MANIFEST.write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"Vendored {sum(len(p['files']) for p in manifest['packages'])} files into {VENDOR}")


def ensure() -> None:
    """Download only when a file is missing or differs; never rewrites the manifest."""
    manifest = json.loads(MANIFEST.read_text())
    expected = {f"{e['name']}@{e['version']}": e for e in manifest["packages"]}
    for pkg in PACKAGES:
        entry = expected.get(f"{pkg['name']}@{pkg['version']}")
        if entry is None or entry["integrity"] != pkg["integrity"]:
            sys.exit(f"manifest.json does not describe {pkg['name']}@{pkg['version']}; run with --update")
        ok = all((VENDOR / t).is_file() and sha256((VENDOR / t).read_bytes()) == m["sha256"] for t, m in entry["files"].items())
        if ok:
            continue
        for target, data in fetch(pkg).items():
            if sha256(data) != entry["files"][target]["sha256"]:
                sys.exit(f"npm content of {target} does not match manifest.json")
            (VENDOR / target).parent.mkdir(parents=True, exist_ok=True)
            (VENDOR / target).write_bytes(data)
        print(f"Fetched {pkg['name']}@{pkg['version']} from npm (integrity verified)")
    check(upstream=False)


def check(upstream: bool) -> None:
    manifest = json.loads(MANIFEST.read_text())
    problems = []
    expected_names = set()
    for entry in manifest["packages"]:
        for target, meta in entry["files"].items():
            expected_names.add(target)
            path = VENDOR / target
            if not path.is_file():
                problems.append(f"missing {target}")
            elif sha256(path.read_bytes()) != meta["sha256"]:
                problems.append(f"sha256 mismatch {target}")
    present = {p.relative_to(VENDOR).as_posix() for p in VENDOR.rglob("*") if p.is_file()} - {"manifest.json"}
    problems += [f"unexpected file {name}" for name in sorted(present - expected_names)]
    if upstream:
        for pkg in PACKAGES:
            for target, data in fetch(pkg).items():
                if not (VENDOR / target).is_file() or (VENDOR / target).read_bytes() != data:
                    problems.append(f"differs from npm {pkg['name']}@{pkg['version']}: {target}")
    if problems:
        sys.exit("Vendor check failed:\n  " + "\n  ".join(problems))
    print(f"Vendor check OK ({len(expected_names)} files{', identical to npm' if upstream else ''})")


if __name__ == "__main__":
    if "--check" in sys.argv:
        check(upstream=False)
    elif "--verify-upstream" in sys.argv:
        check(upstream=True)
    elif "--update" in sys.argv:
        write()
    else:
        ensure()
